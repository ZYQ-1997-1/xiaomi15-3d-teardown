/**
 * build-three.mjs
 * Converts three.module.min.js (ESM) into a classic <script>-loadable file
 * that exposes window.THREE. This lets the teardown page run from file://
 * with zero network access and zero build tooling on the viewer's machine.
 *
 * Usage: node build-three.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const sourceCandidates = [
  path.resolve(here, '..', 'lemo-opuscar', 'node_modules', 'three', 'build', 'three.module.min.js'),
  path.resolve(here, '..', 'lemo-opuscar', 'node_modules', 'three', 'build', 'three.module.js'),
];

const sourcePath = sourceCandidates.find((p) => fs.existsSync(p));
if (!sourcePath) {
  console.error('three.module.min.js not found. Checked:', sourceCandidates.join('\n  '));
  process.exit(1);
}

const source = fs.readFileSync(sourcePath, 'utf8');
const exportIndex = source.lastIndexOf('export{');
const exportIndexSpaced = source.lastIndexOf('export {');
const idx = Math.max(exportIndex, exportIndexSpaced);
if (idx < 0) {
  console.error('Could not locate the final export statement.');
  process.exit(1);
}

const exportBlock = source.slice(idx);
const body = source.slice(0, idx);
const match = exportBlock.match(/export\s*\{([\s\S]*?)\};?\s*$/);
if (!match) {
  console.error('Could not parse the export statement.');
  process.exit(1);
}

const entries = match[1]
  .split(',')
  .map((entry) => entry.trim())
  .filter(Boolean)
  .map((entry) => {
    const aliasMatch = entry.match(/^([\w$]+)\s+as\s+([\w$]+)$/);
    if (aliasMatch) return `${aliasMatch[2]}:${aliasMatch[1]}`;
    return `${entry}:${entry}`;
  });

if (entries.length < 100) {
  console.error('Unexpectedly few exports parsed:', entries.length);
  process.exit(1);
}

const output = `/*!
 * three.js r170 — classic-script build generated from three.module.min.js
 * Original: MIT License, Copyright (c) 2010-2024 three.js authors
 * Generated by build-three.mjs — do not edit by hand.
 */
(function () {
'use strict';
${body}
const THREE = {${entries.join(',')}};
window.THREE = THREE;
})();
`;

const outDir = path.join(here, 'vendor');
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'three.js');
fs.writeFileSync(outPath, output);

console.log(`source : ${sourcePath}`);
console.log(`output : ${outPath}`);
console.log(`exports: ${entries.length}`);
console.log(`size   : ${(output.length / 1024).toFixed(1)} KB`);
console.log(`head   : ${output.slice(0, 160).replace(/\n/g, ' ')}`);
