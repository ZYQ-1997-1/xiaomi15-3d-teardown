/**
 * build-single.mjs — bundle the page into one shareable HTML file.
 * Everything (CSS, data, procedural model, app, Three.js) is inlined so the
 * result can be double-clicked or sent to someone without any other files.
 *
 * Note: replacements use callback form, because the inlined Three.js source
 * contains "$&" sequences that String.replace would otherwise expand.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (rel) => fs.readFileSync(path.join(here, rel), 'utf8');
const escapeScript = (code) => code.replace(/<\/script/gi, '<\\/script');

let html = read('index.html');
const css = read('css/style.css');
const three = escapeScript(read('vendor/three.js'));
const screenImage = escapeScript(read('js/screen-image.js'));
const logoImage = escapeScript(read('js/logo-image.js'));
const chipImage = escapeScript(read('js/chip-image.js'));
const data = escapeScript(read('js/data.js'));
const model = escapeScript(read('js/model.js'));
const app = escapeScript(read('js/app.js'));

html = html.replace('<link rel="stylesheet" href="css/style.css" />', () => `<style>\n${css}\n</style>`);
html = html.replace('<script src="vendor/three.js"></script>', () => `<script>\n${three}\n</script>`);
html = html.replace('<script src="js/screen-image.js"></script>', () => `<script>\n${screenImage}\n</script>`);
html = html.replace('<script src="js/logo-image.js"></script>', () => `<script>\n${logoImage}\n</script>`);
html = html.replace('<script src="js/chip-image.js"></script>', () => `<script>\n${chipImage}\n</script>`);
html = html.replace('<script src="js/data.js"></script>', () => `<script>\n${data}\n</script>`);
html = html.replace('<script src="js/model.js"></script>', () => `<script>\n${model}\n</script>`);
html = html.replace('<script src="js/app.js"></script>', () => `<script>\n${app}\n</script>`);

html = html.replace(
  '<title>Xiaomi 15 · 3D 拆解实验室</title>',
  () =>
    '<title>Xiaomi 15 · 3D 拆解实验室</title>\n' +
    '  <!-- Single-file build. Three.js r170 (MIT) inlined. Generated by build-single.mjs. -->'
);

fs.mkdirSync(path.join(here, 'dist'), { recursive: true });
const outPath = path.join(here, 'dist', 'Xiaomi15-3D-Teardown.html');
fs.writeFileSync(outPath, html);

const tags = [...html.matchAll(/<script[^>]*>/g)].map((m) => m[0]);
const external = tags.filter((t) => /\bsrc=/.test(t));
console.log(`single file: ${outPath}`);
console.log(`size: ${(html.length / 1024).toFixed(1)} KB`);
console.log(`script tags: ${tags.length} (${external.length} external)`);
console.log(`css inlined: ${html.includes('<style>')}`);
if (external.length) {
  console.error('external scripts remain:', external);
  process.exit(1);
}
